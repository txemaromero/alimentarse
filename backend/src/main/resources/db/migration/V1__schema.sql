-- Esquema inicial de Alimentarse (sección 5 de la especificación).
-- Tablas en minúscula y columnas en MAYÚSCULAS, como en la memoria del TFM.
-- Colación utf8mb4_0900_ai_ci: comparaciones y UNIQUE sin distinguir mayúsculas ni acentos.
-- Desviaciones respecto a la memoria: docs/DECISIONES.md (D-014).

CREATE TABLE roles (
    ID     INT          NOT NULL AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL,
    CONSTRAINT PK_ROLES PRIMARY KEY (ID),
    CONSTRAINT UK_ROLES_NOMBRE UNIQUE (NOMBRE)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE usuarios (
    ID               VARCHAR(100) NOT NULL,
    NOMBRE           VARCHAR(100) NOT NULL,
    APELLIDO1        VARCHAR(100) NOT NULL,
    APELLIDO2        VARCHAR(100) NULL,
    EMAIL            VARCHAR(100) NOT NULL,
    PASSWORD         VARCHAR(100) NOT NULL,
    TOKEN_PASSWORD   VARCHAR(100) NULL,
    TOKEN_EXPIRACION TIMESTAMP    NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_USUARIOS_TOKEN_PASSWORD UNIQUE (TOKEN_PASSWORD)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE usuario_rol (
    USUARIO VARCHAR(100) NOT NULL,
    ROL     INT          NOT NULL,
    CONSTRAINT PK_USUARIO_ROL PRIMARY KEY (USUARIO, ROL),
    CONSTRAINT FK_USUARIO_ROL_USUARIO FOREIGN KEY (USUARIO) REFERENCES usuarios (ID),
    CONSTRAINT FK_USUARIO_ROL_ROL FOREIGN KEY (ROL) REFERENCES roles (ID)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE grupo_ingrediente (
    ID              INT          NOT NULL AUTO_INCREMENT,
    NOMBRE          VARCHAR(100) NOT NULL,
    -- NULL = sin límite semanal (∞)
    RACIONES_SEMANA INT          NULL,
    CONSTRAINT PK_GRUPO_INGREDIENTE PRIMARY KEY (ID),
    CONSTRAINT UK_GRUPO_INGREDIENTE_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT CK_GRUPO_INGREDIENTE_RACIONES CHECK (RACIONES_SEMANA IS NULL OR RACIONES_SEMANA > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE ingredientes (
    ID     INT          NOT NULL AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL,
    GRUPO  INT          NOT NULL,
    CONSTRAINT PK_INGREDIENTES PRIMARY KEY (ID),
    CONSTRAINT UK_INGREDIENTES_NOMBRE UNIQUE (NOMBRE),
    CONSTRAINT FK_INGREDIENTES_GRUPO FOREIGN KEY (GRUPO) REFERENCES grupo_ingrediente (ID)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE tipo_receta (
    ID     INT          NOT NULL AUTO_INCREMENT,
    NOMBRE VARCHAR(100) NOT NULL,
    CONSTRAINT PK_TIPO_RECETA PRIMARY KEY (ID),
    CONSTRAINT UK_TIPO_RECETA_NOMBRE UNIQUE (NOMBRE)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE recetas (
    ID             INT          NOT NULL AUTO_INCREMENT,
    TITULO         VARCHAR(100) NOT NULL,
    -- HTML saneado en el backend
    INSTRUCCIONES  TEXT         NOT NULL,
    FECHA_CREACION TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO        VARCHAR(100) NOT NULL,
    TIPO           INT          NOT NULL,
    -- BOOLEAN es TINYINT(1) en MySQL (sin el aviso de "display width" obsoleto)
    PUBLICADA      BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Nombre del fichero dentro de UPLOAD_DIR
    IMAGEN         VARCHAR(100) NULL,
    -- Minutos
    TIEMPO         INT          NOT NULL,
    COMENSALES     INT          NOT NULL,
    DIFICULTAD     VARCHAR(10)  NOT NULL,
    CONSTRAINT PK_RECETAS PRIMARY KEY (ID),
    CONSTRAINT FK_RECETAS_USUARIO FOREIGN KEY (USUARIO) REFERENCES usuarios (ID),
    CONSTRAINT FK_RECETAS_TIPO FOREIGN KEY (TIPO) REFERENCES tipo_receta (ID),
    -- Comparación binaria: el valor debe escribirse exactamente así, con tilde y mayúscula
    CONSTRAINT CK_RECETAS_DIFICULTAD CHECK (DIFICULTAD COLLATE utf8mb4_bin IN ('Fácil', 'Media', 'Difícil')),
    CONSTRAINT CK_RECETAS_TIEMPO CHECK (TIEMPO > 0),
    CONSTRAINT CK_RECETAS_COMENSALES CHECK (COMENSALES > 0)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE ingrediente_receta (
    INGREDIENTE INT          NOT NULL,
    RECETA      INT          NOT NULL,
    -- Texto libre: "200 gramos", "1 cucharada"
    CANTIDAD    VARCHAR(100) NOT NULL,
    CONSTRAINT PK_INGREDIENTE_RECETA PRIMARY KEY (INGREDIENTE, RECETA),
    CONSTRAINT FK_INGREDIENTE_RECETA_INGREDIENTE FOREIGN KEY (INGREDIENTE) REFERENCES ingredientes (ID),
    CONSTRAINT FK_INGREDIENTE_RECETA_RECETA FOREIGN KEY (RECETA) REFERENCES recetas (ID) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE like_receta (
    USUARIO VARCHAR(100) NOT NULL,
    RECETA  INT          NOT NULL,
    CONSTRAINT PK_LIKE_RECETA PRIMARY KEY (USUARIO, RECETA),
    CONSTRAINT FK_LIKE_RECETA_USUARIO FOREIGN KEY (USUARIO) REFERENCES usuarios (ID),
    CONSTRAINT FK_LIKE_RECETA_RECETA FOREIGN KEY (RECETA) REFERENCES recetas (ID) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE usuario_receta_consumida (
    ID      BIGINT       NOT NULL AUTO_INCREMENT,
    USUARIO VARCHAR(100) NOT NULL,
    RECETA  INT          NOT NULL,
    FECHA   TIMESTAMP    NOT NULL,
    CONSTRAINT PK_USUARIO_RECETA_CONSUMIDA PRIMARY KEY (ID),
    CONSTRAINT FK_USUARIO_RECETA_CONSUMIDA_USUARIO FOREIGN KEY (USUARIO) REFERENCES usuarios (ID),
    CONSTRAINT FK_USUARIO_RECETA_CONSUMIDA_RECETA FOREIGN KEY (RECETA) REFERENCES recetas (ID),
    INDEX IX_USUARIO_RECETA_CONSUMIDA_USUARIO_FECHA (USUARIO, FECHA)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;
