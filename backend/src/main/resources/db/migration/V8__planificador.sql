-- Planificador semanal (D-068): comidas que el usuario piensa hacer. Un hueco (usuario y momento) tiene una sola receta.
CREATE TABLE usuario_receta_planificada (
    ID      BIGINT       NOT NULL AUTO_INCREMENT,
    USUARIO VARCHAR(100) NOT NULL,
    RECETA  INT          NOT NULL,
    FECHA   TIMESTAMP    NOT NULL,
    CONSTRAINT PK_USUARIO_RECETA_PLANIFICADA PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIO_RECETA_PLANIFICADA_HUECO UNIQUE (USUARIO, FECHA),
    CONSTRAINT FK_USUARIO_RECETA_PLANIFICADA_USUARIO FOREIGN KEY (USUARIO) REFERENCES usuarios (ID),
    CONSTRAINT FK_USUARIO_RECETA_PLANIFICADA_RECETA FOREIGN KEY (RECETA) REFERENCES recetas (ID) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_0900_ai_ci;
